/** Presentation scale only: the canonical model still uses a budget of 100. */
export const TENGE_PER_BUDGET_UNIT = 100_000_000;
export const budgetDisclaimer = 'Бюджет и цены в тенге — условные суммы симулятора.';
export const toTenge = (units: number) => Math.round(units * TENGE_PER_BUDGET_UNIT);

export function formatBudget(units: number): string {
  const amount = toTenge(units);
  const absolute = Math.abs(amount);
  const divisor = absolute >= 1_000_000_000 ? 1_000_000_000 : absolute >= 1_000_000 ? 1_000_000 : 1;
  const suffix = divisor === 1_000_000_000 ? ' млрд' : divisor === 1_000_000 ? ' млн' : '';
  return `${(amount / divisor).toLocaleString('ru-RU', { maximumFractionDigits: 2 })}${suffix} ₸`;
}

